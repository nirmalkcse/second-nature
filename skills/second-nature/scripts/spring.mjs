#!/usr/bin/env node
/**
 * spring.mjs — one spring, every platform's dialect.
 *
 *   node spring.mjs --duration 0.4 --bounce 0.2
 *   node spring.mjs --preset snappy
 *   node spring.mjs --stiffness 170 --damping 26        (physical → designer terms)
 *   node spring.mjs --tokens                            (CSS custom properties for every preset)
 *
 * Prints the physical parameters, how long it really takes to settle, and
 * ready-to-paste code for CSS, Motion, SwiftUI, UIKit, Reanimated, Compose
 * and Flutter, so a spring tuned once feels the same everywhere.
 */
import { SPRINGS, springFromBounce, springFromPhysical, springToCSS, settleTime, springAt } from '../assets/physics.js';

const args = Object.fromEntries(
  process.argv.slice(2).reduce((acc, a, i, all) => {
    if (a.startsWith('--')) acc.push([a.slice(2), all[i + 1] && !all[i + 1].startsWith('--') ? all[i + 1] : true]);
    return acc;
  }, []),
);

const n = (v, p = 2) => Number(v.toFixed(p));

if (args.help || args.h) {
  console.log(`Usage:
  node spring.mjs --duration <s> --bounce <-1..1>
  node spring.mjs --preset <${Object.keys(SPRINGS).join('|')}>
  node spring.mjs --stiffness <k> --damping <c> [--mass <m>]
  node spring.mjs --tokens`);
  process.exit(0);
}

if (args.tokens) {
  console.log('/* Generated by scripts/spring.mjs --tokens */');
  for (const [name, spring] of Object.entries(SPRINGS)) {
    const { easing, durationMs } = springToCSS(spring);
    console.log(`  --sn-spring-${name}: ${easing};`);
    console.log(`  --sn-spring-${name}-duration: ${durationMs}ms;`);
  }
  process.exit(0);
}

let spring;
if (args.preset) {
  spring = SPRINGS[args.preset];
  if (!spring) {
    console.error(`Unknown preset "${args.preset}". Try: ${Object.keys(SPRINGS).join(', ')}`);
    process.exit(1);
  }
} else if (args.stiffness) {
  spring = springFromPhysical({ mass: Number(args.mass ?? 1), stiffness: Number(args.stiffness), damping: Number(args.damping ?? 10) });
} else {
  spring = springFromBounce(Number(args.duration ?? 0.5), Number(args.bounce ?? 0));
}

const { mass, stiffness, damping, dampingRatio, duration, bounce } = spring;
const settle = settleTime({ spring });
const css = springToCSS(spring);

let peak = 1;
for (let t = 0; t < settle; t += 1 / 240) peak = Math.max(peak, springAt(t, { spring }).value);
const overshoot = (peak - 1) * 100;

const character =
  bounce <= 0 ? 'no overshoot — the safe default for UI' : bounce < 0.2 ? 'a hint of life' : bounce <= 0.4 ? 'clearly bouncy — reserve for motion a gesture started' : 'toy-like — too much for interface chrome';

console.log(`
Spring   duration ${n(duration)}s · bounce ${n(bounce)}   (${character})
Physics  mass ${n(mass)} · stiffness ${n(stiffness, 1)} · damping ${n(damping, 1)} · damping ratio ${n(dampingRatio)}
Feel     settles in ~${Math.round(settle * 1000)}ms · overshoots ${n(overshoot, 1)}%

CSS (fixed start and end, no gesture velocity)
  transition: transform ${css.durationMs}ms ${css.easing};

Motion / Framer Motion
  transition={{ type: "spring", duration: ${n(duration)}, bounce: ${n(Math.max(bounce, 0))} }}
  transition={{ type: "spring", stiffness: ${n(stiffness, 1)}, damping: ${n(damping, 1)}, mass: ${n(mass)} }}

second-nature physics.js
  animate({ from, to, velocity, spring: springFromBounce(${n(duration)}, ${n(bounce)}) })

SwiftUI
  .animation(.spring(duration: ${n(duration)}, bounce: ${n(bounce)}), value: state)

UIKit (iOS 17+)
  UIView.animate(springDuration: ${n(duration)}, bounce: ${n(bounce)}) { … }

Core Animation
  CASpringAnimation(perceptualDuration: ${n(duration)}, bounce: ${n(bounce)})

React Native Reanimated
  withSpring(to, { mass: ${n(mass)}, stiffness: ${n(stiffness, 1)}, damping: ${n(damping, 1)} })

Jetpack Compose
  spring(dampingRatio = ${n(Math.min(dampingRatio, 1))}f, stiffness = ${n(stiffness, 1)}f)

Flutter
  SpringSimulation(SpringDescription(mass: ${n(mass)}, stiffness: ${n(stiffness, 1)}, damping: ${n(damping, 1)}), from, to, velocity)
`);
